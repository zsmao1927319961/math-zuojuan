def set_q(qid, field, new, tag):
    q = Q[qid]
    old = q.get(field) or ""
    q[field] = new
    applied.append((qid, field, tag, len(old), len(new)))

def edit_q(qid, field, old, new, tag):
    q = Q[qid]
    cur = q.get(field) or ""
    if old not in cur:
        print(f"[MISS] {qid} {field}: anchor not found: {old[:40]!r}")
        sys.exit(1)
    q[field] = cur.replace(old, new, 1)
    applied.append((qid, field, tag, len(cur), len(q[field])))

